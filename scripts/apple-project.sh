#!/usr/bin/env bash
# Generates apps/apple/Manager.xcodeproj and Config/Secrets.plist.
#
# The project file is generated so the tree stays reviewable: XcodeGen owns the
# pbxproj, `project.yml` owns the settings. Secrets.plist is written from the
# env files that already exist for the web app and the Convex backend, so there
# is exactly one place to edit values.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
apple_dir="$root/apps/apple"
backend_env="$root/packages/backend/.env.local"
web_env="$root/apps/web/.env.local"

# Reads KEY=value from an env file without sourcing it (values may contain
# characters bash would expand). Later assignments win, as they do in dotenv.
read_env() {
  local file="$1" key="$2"
  [ -f "$file" ] || return 0
  sed -n "s/^[[:space:]]*\(export[[:space:]]\{0,1\}\)\{0,1\}${key}[[:space:]]*=[[:space:]]*//p" "$file" |
    tail -n 1 |
    sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'\$/\1/" -e 's/[[:space:]]*$//'
}

convex_url="${MANAGER_CONVEX_URL:-${CONVEX_URL:-}}"
if [ -z "$convex_url" ]; then
  convex_url="$(read_env "$backend_env" CONVEX_URL)"
fi
if [ -z "$convex_url" ]; then
  convex_url="$(read_env "$backend_env" VITE_CONVEX_URL)"
fi

clerk_key="${MANAGER_CLERK_PUBLISHABLE_KEY:-${CLERK_PUBLISHABLE_KEY:-}}"
if [ -z "$clerk_key" ]; then
  clerk_key="$(read_env "$web_env" VITE_CLERK_PUBLISHABLE_KEY)"
fi
if [ -z "$clerk_key" ]; then
  clerk_key="$(read_env "$web_env" CLERK_PUBLISHABLE_KEY)"
fi
if [ -z "$clerk_key" ]; then
  clerk_key="$(read_env "$web_env" NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY)"
fi

xml_escape() {
  sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
}

mkdir -p "$apple_dir/Config"
cat >"$apple_dir/Config/Secrets.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by scripts/apple-project.sh. Do not edit or commit. -->
<plist version="1.0">
<dict>
	<key>CONVEX_URL</key>
	<string>$(printf '%s' "$convex_url" | xml_escape)</string>
	<key>CLERK_PUBLISHABLE_KEY</key>
	<string>$(printf '%s' "$clerk_key" | xml_escape)</string>
</dict>
</plist>
PLIST

if [ -z "$convex_url" ] || [ -z "$clerk_key" ]; then
  echo "warning: Config/Secrets.plist is incomplete." >&2
  [ -n "$convex_url" ] || echo "  CONVEX_URL: set it in packages/backend/.env.local (run \`pnpm dev:backend\`)." >&2
  [ -n "$clerk_key" ] || echo "  VITE_CLERK_PUBLISHABLE_KEY: set it in apps/web/.env.local." >&2
  echo "  The app will build but show setup instructions at launch." >&2
fi

if ! command -v xcodegen >/dev/null 2>&1; then
  echo "error: xcodegen is not installed. Run \`brew install xcodegen\`." >&2
  exit 1
fi

cd "$apple_dir"
xcodegen generate --spec project.yml --quiet
echo "Generated apps/apple/Manager.xcodeproj"
